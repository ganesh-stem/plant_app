/*
 * Screenshot tests (Paparazzi) are opt-in because Paparazzi swaps android.jar for
 * layoutlib, which conflicts with plain JVM unit tests:
 *   ./gradlew recordPaparazziDebug -Pscreenshots   -> writes app/src/test/snapshots
 *   ./gradlew verifyPaparazziDebug -Pscreenshots   -> fails on visual regressions
 */
